#!/usr/bin/env python3
"""Generate / verify the doc indexes in CLAUDE.md and .claude/machines/dev.md.

Both indexes are auto-loaded into every agent session, which makes them the most expensive
text in the repo per unit of value. A hand-maintained index drifts into summaries (one grew to a
median 35 words per entry, longest 632) because it is maintained BESIDE the docs it points at.
Here the DOC owns its routing line, in frontmatter, and this regenerates the indexes from those
-- so they cannot drift.

    python tools/kb_index.py            # report drift + coverage, write nothing
    python tools/kb_index.py --write    # regenerate the blocks in place
    python tools/kb_index.py --check    # exit 1 if stale, invisible, or over the byte budget

Doc frontmatter (flat `key: value`):

    ---
    trigger: touching `src/Billing/`, `invoices` table, or joining X to Y
    status: live 2026-08-27 | designed, not built | INERT
    section: app | data | api | tools | framework | plan | process | testing | archive
    supersedes: other-doc.md
    ---

`section` picks BOTH the index and the heading. app/data/api/tools land in CLAUDE.md
(machine-agnostic); framework/plan/process/testing land in machines/dev.md (dev posture only);
archive lands in .claude/kb-archive.md, which is NOT auto-loaded. Keeping the trunk
machine-agnostic is what stops machine profiles inheriting each other's content.

MERGE MODE, and why it is load-bearing: a doc with no frontmatter keeps whatever line its index
already had, so a retrofit can proceed doc by doc with no window in which an index is incomplete.
The fallback must NOT fire for a doc whose section moved it to ANOTHER index -- that silently
resurrects its old line and undoes the move. See `_rows()`.
"""

import argparse
import glob
import os
import re
import sys

MAX_WORDS = 30
# A routing line only has to make you open the doc; the header keeps the full trigger.
TRIGGER_WORDS = 10
STATUS_WORDS = 6

BEGIN = '<!-- KB-INDEX:BEGIN -- generated by tools/kb_index.py from doc frontmatter; do not hand-edit -->'
END = '<!-- KB-INDEX:END -->'

TARGETS = [
    ('CLAUDE.md', [
        ('app', '### App modules'),
        ('data', '### Cross-cutting concerns & data models'),
        ('api', '### External APIs'),
        ('tools', '### Tooling'),
    ]),
    ('.claude/machines/dev.md', [
        ('framework', '### Framework & UI references'),
        ('plan', '### Plans & in-flight work'),
        ('process', '### Process references'),
        ('testing', '### Testing & deployment'),
    ]),
    # NOT auto-loaded. A doc that is purely history sets `section: archive`; its line moves here,
    # out of every session's context, and stays greppable.
    ('.claude/kb-archive.md', [
        ('archive', '## Finished work'),
    ]),
]
SECTION_OF = {k: t for t, secs in TARGETS for k, _ in secs}

# Not docs: decisions.md is reached by anchor breadcrumbs and has its own index (kb_toc.py);
# machine.local.md is the gitignored one-line profile selector; kb-archive.md is our output.
SKIP = {'decisions.md', 'machine.local.md', 'kb-archive.md'}

# Byte budget for what a session auto-loads: CLAUDE.md + machines/dev.md + this machine's
# MEMORY.md. Rules accrete after every failure and are never retired unless something counts
# them. --check warns past WARN and fails past MAX: retire or move a rule to a module doc rather
# than raise the number -- see .claude/decisions.md#auto-loaded-instruction-budget
BUDGET_FILES = ['CLAUDE.md', '.claude/machines/dev.md']
BUDGET_WARN = 70 * 1024
BUDGET_MAX = 75 * 1024


def memory_index_path():
    """This machine's auto-memory index, if it exists: ~/.claude/projects/<slug>/memory/MEMORY.md,
    where the slug is the project path with ':', '\\' and '/' turned into '-'."""
    slug = re.sub(r'[:\\/]', '-', os.path.abspath('.'))
    path = os.path.join(os.path.expanduser('~'), '.claude', 'projects', slug, 'memory', 'MEMORY.md')
    return path if os.path.isfile(path) else None


def budget():
    """-> (total bytes, [(label, bytes)]). MEMORY.md is counted only where it exists."""
    parts = [(p, os.path.getsize(p)) for p in BUDGET_FILES]
    mem = memory_index_path()
    if mem:
        parts.append(('MEMORY.md', os.path.getsize(mem)))
    return sum(b for _, b in parts), parts


def read_frontmatter(path):
    with open(path, encoding='utf-8') as fh:
        if fh.readline().strip() != '---':
            return {}
        meta, key = {}, None
        for line in fh:
            if line.strip() == '---':
                return meta
            m = re.match(r'^([a-z_]+):\s*(.*)$', line)
            if m:
                key = m.group(1)
                meta[key] = m.group(2).strip()
            elif key and line.startswith((' ', '\t')):
                meta[key] += ' ' + line.strip()
            else:
                key = None
    return {}


def clamp(text, words, seps=';,'):
    """Truncate at the last clause boundary that fits, so the line stays readable.

    Order triggers most-identifying-first (paths and symbols before prose) so the part that
    survives is the part that matches a search.
    """
    if len(text.split()) <= words:
        return text
    cut = ' '.join(text.split()[:words])
    at = max(cut.rfind(s) for s in seps)
    return (cut[:at] if at > len(cut) // 2 else cut).rstrip(' ,;') + ' ...'


def short_status(status):
    """First clause only. Parentheticals are dropped WHOLE rather than truncated -- a half-open
    bracket reads as a broken tool. Comma is not a clause break: 'designed, not built' is one
    status whose second half is the load-bearing part."""
    s = re.sub(r'\s*\([^)]*\)', '', status.strip())
    s = re.split(r'\s[-–—]\s|\.\s|;', s, maxsplit=1)[0].strip().rstrip('.,')
    return clamp(s, STATUS_WORDS)


def line_from_meta(path, meta):
    trigger = re.sub(r'\s+', ' ', meta.get('trigger', '')).strip().rstrip('.')
    if not trigger:
        return None
    trigger = clamp(trigger, TRIGGER_WORDS)
    text = f'Read before {trigger}' if trigger[0].islower() else trigger
    if not text.endswith('...'):
        text += '.'
    status = short_status(meta.get('status', ''))
    if status:
        text += f' ({status})'
    sup = meta.get('supersedes', '').strip()
    if sup:
        text += f' **Newer than `{sup}`.**'
    return f'- `{path}` — {text}'


def parse_existing(text, headings):
    """Existing index lines in one target -> [(section_key, path, line)]."""
    block = re.search(re.escape(BEGIN) + r'\n(.*?)' + re.escape(END), text, flags=re.S)
    if block:
        body = block.group(1)
    else:
        starts = [text.index(h) for _, h in headings if h in text]
        if not starts:
            return []
        body = text[min(starts):]
    lookup = {h: k for k, h in headings}
    out, section = [], None
    for line in body.split('\n'):
        if line.strip() in lookup:
            section = lookup[line.strip()]
            continue
        m = re.match(r'^- `(\.claude[\\/][a-z0-9._-]+\.md)`', line)
        if m and section:
            out.append((section, m.group(1).replace('\\', '/'), line.rstrip()))
    return out


def collect():
    """-> (generated{path: (section, line)}, no_section[])"""
    generated, no_section = {}, []
    for path in sorted(glob.glob('.claude/*.md')):
        path = path.replace('\\', '/')
        if os.path.basename(path) in SKIP:
            continue
        meta = read_frontmatter(path)
        if not meta:
            continue
        line = line_from_meta(path, meta)
        if not line:
            continue
        sec = meta.get('section')
        if sec not in SECTION_OF:
            no_section.append(path)
            continue
        generated[path] = (sec, line)
    return generated, no_section


def _rows(existing, generated, headings):
    """Index lines for one target, preserving the curated order."""
    keys = {k for k, _ in headings}
    known = {p: (s, l) for s, p, l in existing}
    rows = {k: [] for k in keys}
    for _, path, line in existing:
        sec_gen = generated.get(path, (None,))[0]
        if sec_gen is not None and sec_gen not in keys:
            continue          # moved to ANOTHER index -- do not resurrect it here
        if path in generated:
            rows[generated[path][0]].append(generated[path][1])
        else:
            rows[known[path][0]].append(line)
    for path in sorted(generated):
        sec, line = generated[path]
        if sec in keys and path not in known:
            rows[sec].append(line)
    return rows


def build():
    generated, no_section = collect()
    blocks, hand_all = {}, []
    covered = set()
    for target, headings in TARGETS:
        text = open(target, encoding='utf-8').read()
        existing = parse_existing(text, headings)
        rows = _rows(existing, generated, headings)
        out = [BEGIN, '']
        for key, heading in headings:
            if rows.get(key):
                out += [heading] + rows[key] + ['']
        out.append(END)
        blocks[target] = (text, '\n'.join(out))
        for _, p, _ in existing:
            covered.add(p)
            if p not in generated:
                hand_all.append(p)
    covered |= set(generated)
    invisible = [p.replace('\\', '/') for p in sorted(glob.glob('.claude/*.md'))
                 if p.replace('\\', '/') not in covered
                 and os.path.basename(p) not in SKIP]
    return blocks, generated, sorted(set(hand_all)), invisible, no_section


def write_if_changed(path, text):
    """Write `text` to `path` only if the content differs, keeping the file's own line endings.

    An unconditional text-mode write on Windows flips a file to CRLF, leaving it "modified" with
    no content change -- which on a shared checkout reads as some other session's edit.
    """
    raw = open(path, 'rb').read()
    nl = '\r\n' if b'\r\n' in raw else '\n'
    if raw.decode('utf-8').replace('\r\n', '\n') == text:
        return False
    with open(path, 'wb') as fh:
        fh.write(text.replace('\n', nl).encode('utf-8'))
    return True


def splice(text, block, headings):
    if BEGIN in text:
        return re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda _: block, text, flags=re.S)
    starts = [text.index(h) for _, h in headings if h in text]
    if not starts:
        return text.rstrip('\n') + '\n\n' + block + '\n'
    start = min(starts)
    end = text.index('\n---\n', start) if '\n---\n' in text[start:] else len(text)
    return text[:start] + block + text[end:]


def main():
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()

    blocks, generated, hand, invisible, no_section = build()
    stale = []
    written = []
    for target, headings in TARGETS:
        text, block = blocks[target]
        cur = re.search(re.escape(BEGIN) + r'.*?' + re.escape(END), text, flags=re.S)
        if not cur or cur.group(0) != block:
            stale.append(target)
        if args.write:
            # Say what is being overwritten. ANOTHER SESSION may have hand-edited the block, and
            # a silent --write discards that work with no trace.
            before = cur
            if before:
                pat = r'^- `(\.claude[\/][a-z0-9._-]+\.md)`.*$'
                was = {m.group(1): m.group(0) for m in re.finditer(pat, before.group(0), re.M)}
                now = {m.group(1): m.group(0) for m in re.finditer(pat, block, re.M)}
                for k in sorted(k for k in was if k in now and was[k] != now[k]):
                    print(f'  rewrote {os.path.basename(k)} ({len(was[k].split())}w -> {len(now[k].split())}w)')
                for k in sorted(k for k in was if k not in now):
                    print(f'  REMOVED from {os.path.basename(target)}: {k}')
            if write_if_changed(target, splice(text, block, headings)):
                written.append(os.path.basename(target))
            else:
                print(f'  {os.path.basename(target)}: already current, not rewritten')

    per = {}
    for p, (s, _) in generated.items():
        per[SECTION_OF[s]] = per.get(SECTION_OF[s], 0) + 1
    summary = ' | '.join(f'{os.path.basename(t)}: {per.get(t, 0)}' for t, _ in TARGETS)
    if args.write:
        print(f"wrote {', '.join(written) if written else 'nothing (all current)'} — "
              f'{len(generated)} generated ({summary})')
    else:
        print(f'{len(generated)} generated ({summary}) | {len(hand)} hand-written | '
              + ('STALE: ' + ', '.join(stale) if stale else 'all indexes current'))

    if hand:
        print(f'  no frontmatter yet ({len(hand)}): '
              + ', '.join(os.path.basename(p) for p in hand[:6]) + (' ...' if len(hand) > 6 else ''))
    if no_section:
        print(f'  !! headered but section is missing/unknown ({len(no_section)}):')
        for p in no_section:
            print(f'      {p}')
    if invisible:
        print(f'  !! INVISIBLE - no header and in no index ({len(invisible)}):')
        for p in invisible:
            print(f'      {p}')
    for target, _ in TARGETS:
        for l in blocks[target][1].split('\n'):
            if l.startswith('- `') and len(l.split()) > MAX_WORDS + 3:
                print(f'  !! over {MAX_WORDS} words ({os.path.basename(target)}): {l[:80]}...')

    total, parts = budget()
    detail = ' + '.join(f'{os.path.basename(p)} {b / 1024:.1f}' for p, b in parts)
    over = total > BUDGET_MAX
    if over:
        print(f'  !! auto-loaded {total / 1024:.1f} KB is OVER the {BUDGET_MAX // 1024} KB budget ({detail}) '
              '- retire or move a rule to its module doc, never raise the budget unasked')
    elif total > BUDGET_WARN:
        print(f'  ! auto-loaded {total / 1024:.1f} KB, near the {BUDGET_MAX // 1024} KB budget ({detail})')
    else:
        print(f'  auto-loaded {total / 1024:.1f} KB of {BUDGET_MAX // 1024} KB budget ({detail})')

    if args.check and (stale or invisible or no_section or over):
        sys.exit(1)


if __name__ == '__main__':
    main()
