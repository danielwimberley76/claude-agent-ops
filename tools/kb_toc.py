#!/usr/bin/env python3
"""Generate / verify the anchor index at the top of .claude/decisions.md.

decisions.md grows without bound and is reached almost entirely by code breadcrumbs
(`// ... — see .claude/decisions.md#anchor`). That works when you already know the anchor. It
gives you no way to discover that an entry EXISTS by topic, which is the common case when you are
about to make a decision someone already made.

This writes a scannable anchor->gist list between markers so the file can be previewed by reading
its top instead of grepped blind.

    python tools/kb_toc.py            # report drift, write nothing
    python tools/kb_toc.py --write    # regenerate the block in place
    python tools/kb_toc.py --check    # exit 1 if stale

Three anchor conventions are parsed, none rewritten: `{#id}` suffixes, bare-slug heading text,
and raw `<a id="..."></a>` tags.
"""

import argparse
import re
import sys
from pathlib import Path

DOC = Path('.claude/decisions.md')
BEGIN = '<!-- ANCHOR-INDEX:BEGIN -- generated by tools/kb_toc.py, do not hand-edit -->'
END = '<!-- ANCHOR-INDEX:END -->'
GIST_MAX = 96

# Headings that group entries rather than being entries themselves. ⚙️ Your categories here.
CATEGORY = {'database', 'deployment', 'runtime', 'process'}


def strip_md(text):
    text = re.sub(r'`([^`]*)`', r'\1', text)
    text = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', text)
    text = re.sub(r'\*\*([^*]*)\*\*', r'\1', text)
    text = re.sub(r'\*([^*]*)\*', r'\1', text)
    return re.sub(r'\s+', ' ', text).strip()


def first_sentence(text):
    """First sentence, but don't split on a period inside an identifier."""
    m = re.search(r'(?<![A-Za-z0-9_])\.(?:\s|$)', text)
    return text[:m.start()].strip() if m else text.strip()


def trim_gist(gist):
    gist = re.sub(r'\{#[a-z0-9-]+\}|<a id="[a-z0-9-]+"></a>', '', gist)
    gist = re.sub(r'\s*\(20\d\d-\d\d-\d\d\)\s*$', '', gist).strip(' .')
    if len(gist) > GIST_MAX:
        gist = gist[:GIST_MAX].rsplit(' ', 1)[0] + '...'
    return gist


def body_gist(lines, start, level):
    """Gist for a bare-slug heading: a deeper descriptive heading right under it, else the first
    real prose line, with any leading label ("Context:", "Decision (date):") stripped."""
    for line in lines[start + 1:start + 14]:
        s = line.strip()
        if not s:
            continue
        h = re.match(r'^(#+)\s+(.*)', s)
        if h:
            if len(h.group(1)) > level:
                return strip_md(re.sub(r'\{#[a-z0-9-]+\}|<a id="[a-z0-9-]+"></a>', '', h.group(2))).strip()
            break
        if s.startswith(('|', '```', '>', '<!--', '- ', '* ')) or re.match(r'^\d+\.', s):
            continue
        s = strip_md(s)
        s = re.sub(r'^(Date|Author|Owner|Status|Context|Decision|Problem|Summary|TL;DR)\b'
                   r'\s*(\([^)]*\))?\s*[:\-]\s*', '', s, flags=re.I).strip()
        if not s or re.fullmatch(r'\(?20\d\d-\d\d-\d\d\)?[\s.,]*(\([^)]*\))?[\s.]*', s):
            continue
        s = re.sub(r'^\(?20\d\d-\d\d-\d\d\)?\s*(\([^)]*\))?\s*[.\-—:]*\s*', '', s).strip()
        return first_sentence(s)
    return ''


def parse(lines):
    """-> list of (anchor, gist, lineno), in document order."""
    out, seen = [], set()
    for i, line in enumerate(lines):
        m = re.match(r'^(#+)\s+(.*)', line)
        if not m:
            # A bare `<a id="...">` on its own line just BELOW the heading it anchors.
            tag = re.fullmatch(r'\s*<a id="([a-z0-9-]+)"></a>\s*', line)
            if tag and tag.group(1) not in seen:
                for j in range(i - 1, max(i - 4, -1), -1):
                    hm = re.match(r'^(#+)\s+(.*)', lines[j])
                    if hm:
                        seen.add(tag.group(1))
                        out.append((tag.group(1), trim_gist(strip_md(hm.group(2))), j + 1))
                        break
            continue
        raw = m.group(2)
        explicit = re.search(r'\{#([a-z0-9-]+)\}', raw) or re.search(r'<a id="([a-z0-9-]+)"></a>', raw)
        clean = strip_md(re.sub(r'\{#[a-z0-9-]+\}|<a id="[a-z0-9-]+"></a>', '', raw)).strip()

        anchor = explicit.group(1) if explicit else None
        if not anchor:
            # A heading with no explicit id is an anchor only when its own text IS a slug.
            # Without that test, any prose heading gets published as an anchor nothing links to.
            if re.search(r'\s', clean) or not re.fullmatch(r'[a-z0-9-]+', clean) or clean in CATEGORY:
                continue
            anchor = clean

        if anchor in seen:
            continue
        seen.add(anchor)

        gist = '' if clean.replace('-', '').replace(' ', '') == anchor.replace('-', '') else clean
        if not gist:
            gist = body_gist(lines, i, len(m.group(1)))
        out.append((anchor, trim_gist(gist), i + 1))
    return out


def render(entries):
    rows = [
        BEGIN,
        '',
        '## Anchor index',
        '',
        'Every anchored decision in this file, alphabetically; grep the anchor to reach it.',
        'Regenerate with `python tools/kb_toc.py --write`.',
        '',
    ]
    # No line numbers and no entry count: either one changes on every new entry and rewrites the
    # whole block, so two branches that each add a decision would always conflict.
    for anchor, gist, _ in sorted(entries):
        rows.append(f'- [`{anchor}`](#{anchor}){" — " + gist if gist else ""}')
    rows += ['', END]
    return '\n'.join(rows)


def assemble(body, block):
    """Splice the index block into the index-stripped body, after the intro's first '---' rule."""
    at = next((i for i, l in enumerate(body) if l.strip() == '---'), 0) + 1
    rebuilt = '\n'.join(body[:at] + ['', block, ''] + body[at:])
    return re.sub(r'\n{4,}', '\n\n\n', rebuilt)


def main():
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()

    if not DOC.exists():
        sys.exit(f'not found: {DOC} (run from the project root)')

    text = DOC.read_text(encoding='utf-8')
    stripped = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n*', '', text, flags=re.S)
    body = stripped.split('\n')
    entries = parse(body)
    block = render(entries)
    rebuilt = assemble(body, block)

    if args.write:
        raw = DOC.read_bytes()
        nl = '\r\n' if b'\r\n' in raw else '\n'
        if raw.decode('utf-8').replace('\r\n', '\n') == rebuilt:
            print(f'anchor index already current — {len(entries)} entries, not rewritten')
            return
        DOC.write_bytes(rebuilt.replace('\n', nl).encode('utf-8'))
        print(f'wrote anchor index to {DOC} — {len(entries)} entries')
        return
    current = re.search(re.escape(BEGIN) + r'.*?' + re.escape(END), text, flags=re.S)
    stale = not current or current.group(0) != block
    print(f'{len(entries)} anchors — index is ' + ('STALE, run --write' if stale else 'current'))
    missing = [a for a, g, _ in entries if not g]
    if missing:
        print(f'  {len(missing)} anchor(s) with no gist: {", ".join(missing[:8])}')
    if args.check and stale:
        sys.exit(1)


if __name__ == '__main__':
    main()
